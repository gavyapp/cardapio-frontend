// Parâmetros da URL que abrem os editores do catálogo no painel. O botão
// "Novo …" do cabeçalho e a lista (navegador) precisam do mesmo nome.

/** "?grupo=novo" ou "?grupo=<id>" abre o editor de grupo de complementos. */
export const GROUP_PARAM = "grupo";

/** Valor do parâmetro para criar um item novo. */
export const NEW_ITEM = "novo";

/** "?produto=novo" ou "?produto=<id>" abre o editor de produto. */
export const PRODUCT_PARAM = "produto";

/** "?busca=<texto>" filtra a lista de produtos. */
export const SEARCH_PARAM = "busca";
